}

// ---------------------------------------------------------------------------
// URL del backend. Se lee de local.properties (no se sube al repositorio):
//
//   api.baseUrl=http://10.0.2.2:8080/api/        <- emulador de Android Studio (por defecto)
//   api.baseUrl=http://192.168.1.50:8080/api/    <- celular real: IP de tu PC en la red WiFi
// ---------------------------------------------------------------------------
val localProps = Properties().apply {
    val f = rootProject.file("local.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
val apiBaseUrl: String = localProps.getProperty("api.baseUrl") ?: "http://10.0.2.2:8080/api/"

// ---------------------------------------------------------------------------
// Firma del APK release. Se lee de keystore.properties (ver keystore.properties.example).
// Si el archivo no existe, el release se genera sin firmar.
// ---------------------------------------------------------------------------
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    namespace = "cl.DSY1105.reservasalas"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "cl.DSY1105.reservasalas"
        // 26 porque el ícono adaptativo (mipmap-anydpi-v26) no existe en versiones anteriores.
        minSdk = 26
        targetSdk = 36
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

        buildConfigField("String", "API_BASE_URL", "\"$apiBaseUrl\"")
    }

    signingConfigs {
        if (keystoreProps.isNotEmpty()) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            optimization {
                enable = false
            }
            if (keystoreProps.isNotEmpty()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
}

